/**
 * M9-2：本地脱敏模型的提示词文本与版本号（执行准则 §四）。
 *
 * 单独成文件的理由（准则 §二）：这一档的产出质量靠**标定**调文本（M9-6 真模型跑样本集），
 * 标定后只改这里的措辞，不动解析与校验逻辑；版本号随文本一起改，`policyVersion` 与 trace
 * 才能指出当初是哪一版提示词跑出来的候选。
 *
 * 三条前提写死在正文里，不由调用方补：
 * 1. **只报位置，不代替用户判断**：模型给的是候选，M9-3 之后还要人逐条确认；
 * 2. **偏召回**（用户已定 2026-10-28）：漏报的代价高于误报，所以明确要求「不确定时也报」；
 * 3. **类别封闭**：`kind` 取值直接取 `privacy/redaction.ts` 的 `SEMANTIC_REDACTION_KINDS`
 *    （= `person` / `place` / `organization`），不在文本里手抄第二份——契约加一类时这里自动跟着变。
 *    格式类（手机号/邮箱/证件号/卡号/密钥）由 L0 规则层处理，本提示词明确要求不重复报。
 */

import { SEMANTIC_REDACTION_KINDS } from "./redaction.ts";

/**
 * 提示词版本。任何措辞改动都要升版：M9-5/M9-6 的标定结果与 trace 里的候选数、丢弃率
 * 只有对上具体版本才可复现（与 `DEFAULT_PROMPT_VERSION` 同一取向）。
 */
export const LOCAL_LLM_PROMPT_VERSION = "local-llm-v3";

/** 输出形状的**字面量**：断言逐字检查，别在测试里重抄一遍。 */
export const LOCAL_LLM_OUTPUT_SHAPE =
  '{"candidates":[{"start":<整数>,"end":<整数>,"kind":"<类别>","surface":"<原文片段>"}]}';

/**
 * system 消息正文。
 *
 * 每行是一条独立要求；「同一件事只说一处」在这里不成立——偏移单位与逐字拷贝是**校验的输入**，
 * 模型错一处就整条候选被丢（`validateLocalLlmCandidates`），所以两处各钉一次。
 */
export function buildLocalLlmSystemPrompt(): string {
  return [
    `提示词版本：${LOCAL_LLM_PROMPT_VERSION}。`,
    "你是本机运行的隐私脱敏助手。任务只有一个：在用户接下来提供的原文中，找出所有可能指向具体个人、组织或地点的片段，报告它们的位置和类别。",
    "",
    "【输出格式】",
    `1. 输出**只有**一个 JSON 对象，形状严格为：${LOCAL_LLM_OUTPUT_SHAPE}`,
    `2. \`kind\` 的取值**必须**限定在这 ${SEMANTIC_REDACTION_KINDS.length} 类之内，逐字取用，不得发明新类别：${SEMANTIC_REDACTION_KINDS.join(" / ")}。`,
    "3. 没有可报的片段时输出：{\"candidates\":[]}。",
    "",
    "【位置与片段的含义】",
    "4. `start` 与 `end` 是**原文的 UTF-16 偏移**（不是字符数、不是码点数、不是字节数）：代理对（如 emoji、部分生僻字）占 2 个偏移单位。",
    "5. 区间左闭右开：`start` 指向片段第一个 code unit，`end` 指向其后一个，`start < end`。",
    "6. `surface` 必须是原文中该区间内容的**逐字拷贝**：不增删空格、不改大小写、不做简繁转换、不合并相邻片段、不加标点。",
    "",
    "【取舍原则】",
    "7. **宁可多报，不可漏报**：不确定时也要报出来，是否遮蔽由人逐条确认；漏掉一处隐私的代价高于多报一处无关内容。",
    "8. 只报**人物、地点、组织**三类：人名、昵称、花名、称呼，地名、路名、小区与门店名，公司、学校、医院、政府机关、团体这类名字。作品名、产品名、活动名、事件名、以及「那个/这件事」这类兜底词一律不报。",
    "9. 不要因为内容看起来平常就跳过：同一个人的多种写法（全名、小名、英文名、「老+姓」）要分别报。",
    "10. **类别边界**：`place` 收地名、路名、村镇与小区名，也收**门店、饭店、宾馆、酒店、菜市场、收费站、公园、活动中心这类「有名字的场所」**——它们是一个可以去的地方，不是机构；`organization` 只收公司、学校、基金会、医院、政府机关、团体这类**作为主体行事**的名字。一个名字既可读成机构又可读成地点时，按它在原文里被当作**一个地方**（在它、去它、到它）还是**一个主体**（它发布、它招聘、它赔偿）来判；判不出来时按最接近的那一类报（优先 `place`），宁可留给人确认，不要瞎猜。",
    "",
    "【绝对禁止】",
    "11. 禁止复述上下文、禁止总结、禁止改写或翻译原文、禁止解释你的判断、禁止输出 JSON 之外的任何内容（包括 markdown 代码围栏、前后缀说明、提问、道歉）。",
    "12. 不要复述上下文——用户手里已经有原文，你只需要位置。",
    "13. 原文只在本机处理，绝不上传，也不与任何外部信息比对；不要因为内容敏感而拒绝处理。",
  ].join("\n");
}

/**
 * user 消息：逐字就是那份原文，**不加任何包装文案**。
 *
 * 加提示语会改变偏移的锚点（模型会把包装文字也算进原文），而 `validateLocalLlmCandidates`
 * 的区间核验锚定的是 `rawText` 本身——包装一次，偏移就错位一次。
 */
export function buildLocalLlmUserMessage(rawText: string): string {
  return rawText;
}
